export function shortName(ticker: string): string {
  return DIRECTORY[ticker] ?? ticker;
}

export function fold(input: string): string {
  return input
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .toLowerCase();
}

export function cleanTicker(input: string): string {
  return input
    .trim()
    .toUpperCase()
    .replace(/(\.VN|\.HN)$/i, "")
    .replace(/[^A-Z0-9]/g, "")
    .slice(0, 12);
}
